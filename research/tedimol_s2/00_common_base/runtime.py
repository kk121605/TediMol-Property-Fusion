def seed_all(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False


def make_diffusion(sample_steps=None):
    if sample_steps is None:
        times = range(2000)
    else:
        if not 2 <= sample_steps <= 2000 or 2000 % sample_steps:
            raise ValueError('sample_steps must divide 2000 and be in [2,2000]')
        # Identical to the handoff range(0, 2000, 10) at 200 steps.
        times = range(0, 2000, 2000//sample_steps)
    return SpacedDiffusion(use_timesteps=times, betas=gd.get_named_beta_schedule('sqrt', 2000),
        model_mean_type=gd.ModelMeanType.START_X, model_var_type=gd.ModelVarType.FIXED_LARGE,
        loss_type=gd.LossType.E2E_MSE, rescale_timesteps=True, model_arch='transformer', training_mode='e2e')


def atomic_torch_save(value, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    torch.save(value, tmp)
    os.replace(tmp, path)


def provenance(manifest, cache_meta):
    return dict(vocab_sha256=manifest['vocab_sha256'],
                train_csv_sha256=manifest['splits']['train_ChemBI']['sha256'],
                data_manifest_sha256=sha256(ROOT / 'data' / 'manifest.json'),
                text_cache_identity={k: cache_meta[k] for k in ('csv_sha256','ids','encoder_hashes','length','dtype','attention_mask_passed','transformers_version','cache_sha256','preprocess_sha256')},
                code_sha256=source_hashes())


def load_checkpoint(path, tokenizer, device='cuda', use_ema=True):
    # Only consume checkpoints generated by this local run, never arbitrary uploads.
    checkpoint = torch.load(path, map_location='cpu', weights_only=False)
    if checkpoint['format'] != 'tedimol-senior-v2-vocab323':
        raise ValueError('Use a checkpoint produced by this vocab323 package, not the retired vocab269 package')
    if checkpoint['provenance']['vocab_sha256'] != sha256(tokenizer.path):
        raise ValueError('Checkpoint vocabulary hash mismatch')
    if checkpoint['config']['max_length'] != tokenizer.max_length:
        raise ValueError('Checkpoint sequence length mismatch')
    if checkpoint['provenance']['code_sha256'] != source_hashes():
        raise ValueError('Code changed since checkpoint. Restore the recorded package before sampling/resume.')
    if checkpoint['config']['runtime_versions'] != runtime_versions():
        raise ValueError('Runtime dependency versions changed since checkpoint')
    model = TransformerNetModel2(len(tokenizer), **checkpoint['config']['model']).to(device)
    model.load_state_dict(checkpoint['model'])
    if use_ema:
        with torch.no_grad():
            for name, param in model.named_parameters():
                param.copy_(checkpoint['ema'][name].to(device))
    return model, checkpoint
